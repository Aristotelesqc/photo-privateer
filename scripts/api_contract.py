"""Export FastAPI OpenAPI and deterministic TypeScript contracts offline.

The small generator supports the schema constructs actually emitted by this
application and fails closed on unsupported constructs. It does not install or
invoke a second TypeScript compiler. --check never rewrites tracked artifacts.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def load_schema() -> dict:
    # Imports create cache directories. Keep even schema-only tooling isolated
    # from the user's catalog and credentials. No lifespan/providers are run.
    with tempfile.TemporaryDirectory(prefix="photo_privateer_contract_") as directory:
        previous = os.environ.get("PHOTO_PRIVATEER_DATA_DIR")
        os.environ["PHOTO_PRIVATEER_DATA_DIR"] = directory
        sys.path.insert(0, str(ROOT))
        try:
            from backend.main import app
            app.openapi_schema = None
            schema = app.openapi()
            return {**schema, "paths": {key: value for key, value in schema["paths"].items() if key.startswith("/api/")}}
        finally:
            if previous is None:
                os.environ.pop("PHOTO_PRIVATEER_DATA_DIR", None)
            else:
                os.environ["PHOTO_PRIVATEER_DATA_DIR"] = previous


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        prefix = "#/components/schemas/"
        if not schema["$ref"].startswith(prefix):
            raise ValueError(f"Unsupported reference: {schema['$ref']}")
        return f"ApiSchemas[{json.dumps(schema['$ref'][len(prefix):])}]"
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "allOf" in schema or "oneOf" in schema:
        raise ValueError("Unsupported composed schema; extend generator explicitly")
    kind = schema.get("type")
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)};'
                  for name, value in sorted(schema.get("properties", {}).items())]
        additional = schema.get("additionalProperties", False)
        if additional:
            fields.append(f"[key: string]: {ts_type(additional) if isinstance(additional, dict) else 'unknown'};")
        return "{ " + " ".join(fields) + " }"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" else "string"
    if kind in {"number", "integer"}:
        return "number"
    if kind in {"boolean", "null"}:
        return kind
    # ValidationError.input is deliberately unspecified JSON. Consumers must
    # narrow it; never substitute any. Untyped success responses still fail below.
    if set(schema) <= {"title", "description", "default", "example", "examples"}:
        return "unknown"
    raise ValueError(f"Unsupported/untyped schema: {schema}")


def generate_types(schema: dict) -> str:
    lines = ["// Generated by scripts/api_contract.py. Do not edit.", "export interface ApiSchemas {"]
    for name, definition in sorted(schema["components"]["schemas"].items()):
        lines.append(f"  {json.dumps(name)}: {ts_type(definition)};")
    lines.extend(["}", "", "export interface ApiOperations {"])
    for path, methods in sorted(schema["paths"].items()):
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "patch", "put", "delete", "options", "head"}:
                continue
            members = []
            for location in ["query", "path"]:
                params = {p["name"]: p["schema"] for p in operation.get("parameters", []) if p["in"] == location}
                required = [p["name"] for p in operation.get("parameters", []) if p["in"] == location and p.get("required")]
                members.append(f"{location}: {ts_type({'type': 'object', 'properties': params, 'required': required})};")
            content = operation.get("requestBody", {}).get("content", {})
            body = ts_type(content["application/json"]["schema"]) if "application/json" in content else "never"
            members.append(f"body: {body};")
            responses = []
            for status, response in operation.get("responses", {}).items():
                if status.isdigit() and 200 <= int(status) < 300:
                    for media in response.get("content", {}).values():
                        if not media.get("schema"):
                            raise ValueError(f"Untyped success response: {method} {path}")
                        responses.append(ts_type(media["schema"]))
            members.append(f"response: {' | '.join(dict.fromkeys(responses)) or 'void'};")
            lines.append(f"  {json.dumps(method.upper() + ' ' + path)}: {{ {' '.join(members)} }};")
    lines.extend(["}", ""])
    return "\n".join(lines)


def artifacts(schema: dict) -> dict[Path, str]:
    return {
        ROOT / "api/openapi.json": json.dumps(schema, sort_keys=True, indent=2) + "\n",
        ROOT / "frontend/src/api/generated.ts": generate_types(schema),
    }


def stale_artifacts(expected: dict[Path, str]) -> list[Path]:
    return [path for path, content in expected.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected_artifacts = artifacts(load_schema())
    stale = stale_artifacts(expected_artifacts) if args.check else []
    if not args.check:
        for path, expected in expected_artifacts.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("Stale API contracts: " + ", ".join(str(path.relative_to(ROOT)) for path in stale) + ". Run python scripts/api_contract.py.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
